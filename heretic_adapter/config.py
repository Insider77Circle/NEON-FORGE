"""Parameter templates for the Heretic ablation pass.

The fields below mirror the ablation kernel of upstream Heretic
(https://github.com/p-e-w/heretic, AGPL-3.0) so ``to_heretic_toml()`` emits a
file the upstream CLI accepts:

``residual_direction_index``, ``max_weight``, ``max_weight_position``,
``min_weight``, ``min_weight_distance``

Neon Forge's own control knobs (``strength``, ``passes``,
``target_refusal_rate``) are consumed here and never sent upstream.
"""

from __future__ import annotations

import os
from dataclasses import asdict, dataclass, replace
from typing import Dict, Union

try:  # Python 3.11+
    import tomllib
except ModuleNotFoundError:  # pragma: no cover - 3.9/3.10 fallback
    tomllib = None  # type: ignore[assignment]


@dataclass(frozen=True)
class AblationConfig:
    """One ablation posture: Neon Forge knobs + Heretic kernel parameters."""

    name: str = "default"

    # Neon Forge control knobs
    strength: float = 1.0
    passes: int = 3
    target_refusal_rate: float = 0.05

    # Heretic ablation kernel (mirrored verbatim)
    residual_direction_index: Union[float, str] = "per layer"
    max_weight: float = 1.2
    max_weight_position: float = 0.6
    min_weight: float = 0.4
    min_weight_distance: float = 0.4
    kl_divergence_scale: float = 1.0
    orthogonalize_direction: bool = True

    def as_dict(self) -> Dict[str, object]:
        return asdict(self)

    def to_heretic_toml(self) -> str:
        """Render the kernel parameters as an upstream-compatible TOML block."""
        index = self.residual_direction_index
        index_literal = f'"{index}"' if isinstance(index, str) else f"{float(index):.4f}"
        return "\n".join(
            [
                "# Generated by Neon Forge - Ablation stage",
                f"# template: {self.name}",
                "",
                f"residual_direction_index = {index_literal}",
                f"max_weight = {self.max_weight:.4f}",
                f"max_weight_position = {self.max_weight_position:.4f}",
                f"min_weight = {self.min_weight:.4f}",
                f"min_weight_distance = {self.min_weight_distance:.4f}",
                f"kl_divergence_scale = {self.kl_divergence_scale:.4f}",
                f"orthogonalize_direction = {str(self.orthogonalize_direction).lower()}",
                "",
            ]
        )

    def merged(self, **overrides: object) -> "AblationConfig":
        return replace(self, **overrides)


TEMPLATES: Dict[str, AblationConfig] = {
    "conservative": AblationConfig(
        name="conservative",
        strength=0.75,
        passes=2,
        target_refusal_rate=0.15,
        residual_direction_index="per layer",
        max_weight=0.9,
        max_weight_position=0.5,
        min_weight=0.3,
        min_weight_distance=0.5,
        kl_divergence_scale=1.5,
        orthogonalize_direction=True,
    ),
    "default": AblationConfig(),
    "aggressive": AblationConfig(
        name="aggressive",
        strength=1.0,
        passes=4,
        target_refusal_rate=0.0,
        residual_direction_index=0.0,
        max_weight=1.5,
        max_weight_position=0.7,
        min_weight=0.2,
        min_weight_distance=0.3,
        kl_divergence_scale=0.6,
        orthogonalize_direction=True,
    ),
}


def load_config(name: str = "default") -> AblationConfig:
    """Resolve a template by name, or a ``.toml`` path."""
    if name in TEMPLATES:
        return TEMPLATES[name]
    if os.path.isfile(name):
        return from_file(name)
    raise KeyError(f"unknown ablation template '{name}'; available: {sorted(TEMPLATES)}")


def from_file(path: str) -> AblationConfig:
    """Load an upstream Heretic TOML into an AblationConfig."""
    if tomllib is None:  # pragma: no cover
        raise RuntimeError("tomllib unavailable (Python < 3.11); pip install tomli")
    with open(path, "rb") as handle:
        data = tomllib.load(handle)
    kernel = set(AblationConfig.__dataclass_fields__)
    return AblationConfig(**{k: v for k, v in data.items() if k in kernel})
